function dist(a, b) {
  const dx = a.x - b.x;
  const dy = a.y - b.y;
  return Math.sqrt(dx * dx + dy * dy);
}

export async function seedPathfinding() {
  console.log("🌱 Bắt đầu nạp hệ thống đồ thị đường đi chi tiết...");

  await query(`
    DROP TABLE IF EXISTS map_edge CASCADE;
    DROP TABLE IF EXISTS map_node CASCADE;

    CREATE TABLE IF NOT EXISTS map_node (
      node_id  VARCHAR(50) PRIMARY KEY,
      name     VARCHAR(120) NOT NULL,
      x        REAL NOT NULL,
      y        REAL NOT NULL,
      category VARCHAR(50)
    );
    CREATE TABLE IF NOT EXISTS map_edge (
      edge_id  SERIAL PRIMARY KEY,
      from_id  VARCHAR(50) REFERENCES map_node(node_id) ON DELETE CASCADE,
      to_id    VARCHAR(50) REFERENCES map_node(node_id) ON DELETE CASCADE,
      distance REAL NOT NULL
    );
  `);

  // Nạp POI nodes
  for (const n of POI_NODES) {
    await query(
      "INSERT INTO map_node (node_id, name, x, y, category) VALUES ($1, $2, $3, $4, $5)",
      [n.id, n.name, n.x, n.y, n.category]
    );
  }

  // Nạp Waypoint nodes
  for (const w of WAYPOINTS) {
    await query(
      "INSERT INTO map_node (node_id, name, x, y, category) VALUES ($1, $2, $3, $4, $5)",
      [w.id, `Lối đi bộ (${w.id})`, w.x, w.y, "waypoint"]
    );
  }

  const allMap = new Map();
  POI_NODES.forEach((n) => allMap.set(n.id, n));
  WAYPOINTS.forEach((w) => allMap.set(w.id, w));

  let edgeCount = 0;
  for (const [u, v] of EDGES) {
    const nodeU = allMap.get(u);
    const nodeV = allMap.get(v);
    if (!nodeU || !nodeV) {
      console.warn(`⚠️ Cảnh báo: Không tìm thấy node ${u} hoặc ${v}`);
      continue;
    }
    const d = dist(nodeU, nodeV);
    const roundedDist = Math.round(d * 100) / 100;

    await query(
      "INSERT INTO map_edge (from_id, to_id, distance) VALUES ($1, $2, $3), ($2, $1, $3)",
      [u, v, roundedDist]
    );
    edgeCount += 2;
  }

  console.log(`✅ Hoàn tất nạp: ${POI_NODES.length} POI, ${WAYPOINTS.length} Waypoints, ${edgeCount} cạnh.`);
}

